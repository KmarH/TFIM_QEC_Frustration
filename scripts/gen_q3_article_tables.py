"""LaTeX tables for the Q3 technical article, generated from runs/q3_sweep/cell_*.json with the
v2 scorer (src/q3_rescore.py) and the Stim survival model (src/q3_scaling.py): nothing is typed by
hand, so a table cannot drift from the data. Writes <out>/tab_*.tex.

Every number is a CLASSICAL PREDICTION under the ASSUMED research/06 noise model; never an H2
result. Usage: python -I scripts/gen_q3_article_tables.py --out docs/article_q3/tables
"""

from __future__ import annotations

import argparse
import glob
import json
import math
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

import numpy as np

from config import CONFIG
from src.noisy_q3_sweep import prior_noise
from src.q3_rescore import MODES, REFS, rescore_cell
from src.q3_scaling import stim_rate_table, survival_curve

QS = CONFIG.q3_scaling
SHORT = {"bare raw": "bare", "bare + Gauss": "bare+G", "Iceberg": "Ice", "Iceberg + Gauss": "Ice+G"}


def load(work):
    cells = []
    for p in sorted(glob.glob(os.path.join(work, "cell_*.json"))):
        with open(p, encoding="utf-8") as fh:
            cells.append(json.load(fh))
    cells.sort(key=lambda c: (c["cell"]["N"], c["cell"]["h"], c["cell"]["lam"]))
    return cells


def score(c):
    st = c["settings"]
    return rescore_cell(c["ideal"], c["bare"], c["ice"], ess_floor=QS.ess_floor,
                        n_traj_bare=st["traj_bare"], n_traj_ice=st["traj_ice"],
                        verdict_k=QS.verdict_k, min_batches=QS.min_batches)


def cell_tex(c):
    cc = c["cell"]
    return f"{cc['N']} & {cc['h']:g} & {cc['lam']:g}"


def _write(out, name, body):
    with open(os.path.join(out, name), "w", encoding="utf-8") as fh:
        fh.write("% generated by scripts/gen_q3_article_tables.py -- do not edit by hand\n" + body)


def tab_cells(cells, out):
    rows = []
    for c in cells:
        cc, st, ice = c["cell"], c["settings"], c["ice"]
        surv = float(ice["acceptance"][-1]) if ice else float("nan")
        ess_end = surv * st["traj_ice"] if ice else float("nan")
        if ice and ice.get("ess") is not None:
            ess_end = float(ice["ess"][-1])
        rows.append(f"{cell_tex(c)} & {cc['physical_qubits']} & {cc['ice_steps']} & "
                    f"{ice['times'][-1] if ice else float('nan'):.2f} & "
                    f"{st['traj_bare']}/{st['traj_ice']} & {st['batches']} & {surv:.4f} & "
                    f"{ess_end:.1f} \\\\")
    _write(out, "tab_cells.tex",
           "\\begin{tabular}{rrr r r r r r r r}\n\\toprule\n"
           "$N$ & $h$ & $\\lambda$ & phys. & window & $t_{\\rm end}$ & traj.\\ bare/Ice & batches"
           " & surv.\\ end & ESS end \\\\\n\\midrule\n" + "\n".join(rows) +
           "\n\\bottomrule\n\\end{tabular}\n")


def _rms(s, m, r):
    x, e = s.rms[(m, r)], s.msd_se[(m, r)]
    if not math.isfinite(x):
        return "\\textit{n.e.}"
    if s.msd[(m, r)] <= e:
        return f"$\\lesssim${math.sqrt(max(e, 0.0)):.4f}"
    return f"{x:.4f}"


def tab_rms(cells, out):
    rows = []
    for c in cells:
        s = score(c)
        cols = [_rms(s, m, r) for r in REFS for m in MODES]
        rows.append(f"{cell_tex(c)} & " + " & ".join(cols) + " \\\\")
    head = " & ".join(SHORT[m] for m in MODES)
    _write(out, "tab_rms.tex",
           "\\begin{tabular}{rrr cccc cccc}\n\\toprule\n"
           "& & & \\multicolumn{4}{c}{vs ideal raw curve} & \\multicolumn{4}{c}{vs ideal "
           "Gauss-conditioned curve} \\\\\n\\cmidrule(lr){4-7}\\cmidrule(lr){8-11}\n"
           f"$N$ & $h$ & $\\lambda$ & {head} & {head} \\\\\n\\midrule\n" + "\n".join(rows) +
           "\n\\bottomrule\n\\end{tabular}\n")


def tab_verdicts(cells, out):
    rows = []
    for c in cells:
        s = score(c)
        for p in s.pairs:
            z = p.gap / p.sigma if math.isfinite(p.gap) and p.sigma > 0 else float("nan")
            zs = f"{z:+.1f}" if math.isfinite(z) else "--"
            v = p.verdict.replace("better:", "better,").replace(" vs ", "\\,/\\,")
            rows.append(f"{cell_tex(c)} & {p.ref} & {SHORT[p.a]} vs {SHORT[p.b]} & {zs} & "
                        f"{v} \\\\")
    _write(out, "tab_verdicts.tex",
           "\\begin{tabular}{rrr l l r l}\n\\toprule\n$N$ & $h$ & $\\lambda$ & ref. & pair & "
           "gap$/\\sigma$ & verdict \\\\\n\\midrule\n" + "\n".join(rows) +
           "\n\\bottomrule\n\\end{tabular}\n")


def tab_survival(cells, out):
    rows = []
    for c in cells:
        cc, ice = c["cell"], c["ice"]
        if ice is None:
            continue
        steps = np.array([cc["ice_steps"]])
        can = float(survival_curve(stim_rate_table(cc["N"], cc["lam"], prior_noise(),
                                                   scope="2q"), steps)[0])
        old = float(survival_curve(stim_rate_table(cc["N"], cc["lam"], prior_noise(),
                                                   scope="2q-legacy"), steps)[0])
        m, n = float(ice["acceptance"][-1]), c["settings"]["traj_ice"]
        dev = (m - can) / math.sqrt(can * (1 - can) / n)
        rows.append(f"{cell_tex(c)} & {m:.4f} & {n} & {can:.4f} & {old:.4f} & {dev:+.1f} \\\\")
    _write(out, "tab_survival.tex",
           "\\begin{tabular}{rrr rrrrr}\n\\toprule\n$N$ & $h$ & $\\lambda$ & measured & traj. & "
           "Stim (every 2q) & Stim (old scope) & dev.\\ [$\\sigma$] \\\\\n\\midrule\n"
           + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def tab_rerun(out):
    rows = []
    for cell in sorted(QS.rerun):
        r = QS.rerun[cell]
        s = float(survival_curve(stim_rate_table(cell[0], cell[2], prior_noise(), scope="2q"),
                                 np.array([r["ice_steps"]]))[0])
        rows.append(f"{cell[0]} & {cell[1]:g} & {cell[2]:g} & {r['ice_steps']} & {s:.4f} & "
                    f"{r['batch_ice']}$\\times${QS.rerun_shards} = {r['traj_ice']} & "
                    f"{r['batch_bare']}$\\times${QS.rerun_shards} = {r['traj_bare']} & "
                    f"{r['traj_ice'] * s:.1f} \\\\")
    _write(out, "tab_rerun.tex",
           "\\begin{tabular}{rrr r r r r r}\n\\toprule\n$N$ & $h$ & $\\lambda$ & window & "
           "$s_{\\rm pred}$ & Iceberg traj. & bare traj. & E[ESS end] \\\\\n\\midrule\n"
           + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True)
    ap.add_argument("--work", default=os.path.join(REPO, "runs", "q3_sweep"))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    cells = load(a.work)
    for fn in (tab_cells, tab_rms, tab_verdicts, tab_survival):
        fn(cells, a.out)
        print("wrote", fn.__name__)
    tab_rerun(a.out)
    print("wrote tab_rerun")


if __name__ == "__main__":
    main()
