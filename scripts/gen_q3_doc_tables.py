"""Write (or check) the v2 tables of docs/q3_scaling.md section 4 from the cell files.

The block between `<!-- v2-tables:begin -->` and `<!-- v2-tables:end -->` is generated, never
typed: the 4 modes x 2 references table and the head-to-head verdicts of DECIDED-8, scored with the
pre-declared rules of DECIDED-10 (src/q3_rescore.py, the call `run_q3_sweep.py --merge` makes).
`--check` regenerates the block and fails if the document differs, so the published tables cannot
drift from runs/q3_sweep/ (it replaces the scratchpad generator of 2026-10-23).

Every number is a CLASSICAL PREDICTION under the ASSUMED research/06 noise model; never an H2
result. Usage: python -I scripts/gen_q3_doc_tables.py [--check]
"""

from __future__ import annotations

import argparse
import glob
import json
import math
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

from config import CONFIG
from src.q3_rescore import MODES, REFS, rescore_cell

DOC = os.path.join(REPO, "docs", "q3_scaling.md")
BEGIN, END = "<!-- v2-tables:begin -->", "<!-- v2-tables:end -->"
QS = CONFIG.q3_scaling


def _cells():
    cells = []
    for p in sorted(glob.glob(os.path.join(REPO, "runs", "q3_sweep", "cell_*.json"))):
        with open(p, encoding="utf-8") as fh:
            cells.append(json.load(fh))
    cells.sort(key=lambda c: (c["cell"]["N"], c["cell"]["h"], c["cell"]["lam"]))
    return cells


def _score(c):
    st = c["settings"]
    return rescore_cell(c["ideal"], c["bare"], c["ice"], ess_floor=QS.ess_floor,
                        n_traj_bare=st["traj_bare"], n_traj_ice=st["traj_ice"],
                        verdict_k=QS.verdict_k, min_batches=QS.min_batches)


def _rms(s, m, r):
    x = s.rms[(m, r)]
    if not math.isfinite(x):
        return "n.e."
    return f"≲{math.sqrt(max(s.msd_se[(m, r)], 0.0)):.4f}" if s.msd[(m, r)] <= s.msd_se[(m, r)] \
        else f"{x:.4f}"


def block() -> str:
    cells = _cells()
    scored = [(c, _score(c)) for c in cells]
    legacy = any(s.se_method[m] == "legacy" for _, s in scored for m in MODES)
    out = [BEGIN,
           ("*Generated by `scripts/gen_q3_doc_tables.py` from `runs/q3_sweep/` - do not edit by "
            "hand. Classical prediction under the ASSUMED research/06 noise model; not an H2 "
            "result.*"),
           "",
           (f"Rules (DECIDED-8, DECIDED-10, fixed before rescoring): Kish ESS >= {QS.ess_floor:g} "
            "at every window point or **no estimate (n.e.)**; bias-corrected rms "
            "`sign(msd) sqrt|msd|`, msd = mean[(O - O_ref)^2 - Var O]; winner only when |gap| > "
            f"{QS.verdict_k:g} x combined SE of the msd's, within one reference."),
           ("**Error bars are LEGACY** (per-point batch SE) for cells without per-batch data; the "
            "jackknife replaces them as the replays land." if legacy else
            "Error bars: delete-one-batch jackknife."),
           "",
           "**rms distance from each ideal curve, over the common encoded window**",
           "",
           "| N | h | λ | " + " | ".join(f"{m} (raw)" for m in MODES) + " | "
           + " | ".join(f"{m} (cond)" for m in MODES) + " |",
           "|" + "---|" * (3 + 2 * len(MODES))]
    for c, s in scored:
        cc = c["cell"]
        row = [str(cc["N"]), f"{cc['h']:g}", f"{cc['lam']:g}"]
        row += [_rms(s, m, r) for r in REFS for m in MODES]
        out.append("| " + " | ".join(row) + " |")
    out += ["", ("**Head to head within each reference** (gap/σ of the msd's; negative = the "
                 "second mode is closer)"), "",
            "| N | h | λ | ref | pair | gap/σ | verdict |", "|---|---|---|---|---|---|---|"]
    for c, s in scored:
        cc = c["cell"]
        for p in s.pairs:
            z = p.gap / p.sigma if math.isfinite(p.gap) and p.sigma > 0 else float("nan")
            zs = f"{z:+.1f}" if math.isfinite(z) else "-"
            out.append(f"| {cc['N']} | {cc['h']:g} | {cc['lam']:g} | {p.ref} | {p.a} vs {p.b} | "
                       f"{zs} | {p.verdict} |")
    out.append(END)
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    with open(DOC, encoding="utf-8") as fh:
        doc = fh.read()
    if BEGIN not in doc or END not in doc:
        raise SystemExit(f"markers {BEGIN} / {END} not found in {DOC}")
    i, j = doc.index(BEGIN), doc.index(END) + len(END)
    new = block()
    if a.check:
        same = doc[i:j].replace("\r\n", "\n") == new
        print("v2 tables match the data" if same else "v2 tables DIFFER from the data")
        sys.exit(0 if same else 1)
    with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(doc[:i] + new + doc[j:])
    print("wrote the v2 block of docs/q3_scaling.md")


if __name__ == "__main__":
    main()
